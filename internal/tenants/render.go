package tenants

import (
	"bytes"
	"fmt"
	"strings"

	"go.yaml.in/yaml/v3"
)

const generatedHeader = "# Code generated by tenantctl from tenants/tenants.yaml. DO NOT EDIT.\n"

type mimirLimits struct {
	Retention                 string   `yaml:"compactor_blocks_retention_period,omitempty"`
	IngestionRate             *float64 `yaml:"ingestion_rate,omitempty"`
	IngestionBurstSize        *int     `yaml:"ingestion_burst_size,omitempty"`
	MaxGlobalSeriesPerUser    *int     `yaml:"max_global_series_per_user,omitempty"`
	RulerMaxRulesPerRuleGroup *int     `yaml:"ruler_max_rules_per_rule_group,omitempty"`
}

// MimirRuntimeConfig renders the per-tenant overrides Mimir reloads at
// runtime (-runtime-config.file), so limits change without restarts.
func (f *File) MimirRuntimeConfig() ([]byte, error) {
	overrides := make(map[string]mimirLimits, len(f.Tenants))
	for _, t := range f.Tenants {
		l := f.Effective(t)
		overrides[t.ID] = mimirLimits{
			Retention:                 l.Retention,
			IngestionRate:             l.IngestionRate,
			IngestionBurstSize:        l.IngestionBurstSize,
			MaxGlobalSeriesPerUser:    l.MaxGlobalSeries,
			RulerMaxRulesPerRuleGroup: l.RulerMaxRulesPerGroup,
		}
	}
	return marshal(map[string]any{"overrides": overrides})
}

type datasource struct {
	Name           string            `yaml:"name"`
	UID            string            `yaml:"uid"`
	Type           string            `yaml:"type"`
	Access         string            `yaml:"access"`
	URL            string            `yaml:"url"`
	IsDefault      bool              `yaml:"isDefault,omitempty"`
	Editable       bool              `yaml:"editable"`
	JSONData       map[string]any    `yaml:"jsonData"`
	SecureJSONData map[string]string `yaml:"secureJsonData"`
}

// AllTenantsUID is the datasource that queries every tenant at once through
// Mimir tenant federation. Results carry a __tenant_id__ label.
const AllTenantsUID = "mimir-all-tenants"

// GrafanaDatasources renders Grafana's datasource provisioning file: a
// Prometheus and an Alertmanager datasource per tenant, plus one federated
// datasource across all tenants. defaultTenant becomes Grafana's default.
func (f *File) GrafanaDatasources(mimirURL, defaultTenant string) ([]byte, error) {
	mimirURL = strings.TrimSuffix(mimirURL, "/")
	var ids []string
	var sources []datasource

	for _, t := range f.Tenants {
		ids = append(ids, t.ID)
		sources = append(sources,
			prometheusDatasource(t.Name, "mimir-"+t.ID, mimirURL, t.ID, "alertmanager-"+t.ID, t.ID == defaultTenant),
			datasource{
				Name:   t.Name + " · Alertmanager",
				UID:    "alertmanager-" + t.ID,
				Type:   "alertmanager",
				Access: "proxy",
				URL:    mimirURL,
				JSONData: map[string]any{
					"implementation":             "mimir",
					"handleGrafanaManagedAlerts": false,
					"httpHeaderName1":            "X-Scope-OrgID",
				},
				SecureJSONData: map[string]string{"httpHeaderValue1": t.ID},
			},
		)
	}
	sources = append(sources,
		prometheusDatasource("All tenants", AllTenantsUID, mimirURL, strings.Join(ids, "|"), "", false))

	return marshal(map[string]any{
		"apiVersion": 1,
		// Remove provisioned datasources whose tenant was deleted.
		"prune":       true,
		"datasources": sources,
	})
}

func prometheusDatasource(name, uid, mimirURL, orgID, alertmanagerUID string, isDefault bool) datasource {
	jsonData := map[string]any{
		"prometheusType":  "Mimir",
		"httpMethod":      "POST",
		"timeInterval":    "15s",
		"httpHeaderName1": "X-Scope-OrgID",
	}
	if alertmanagerUID != "" {
		jsonData["alertmanagerUid"] = alertmanagerUID
	}
	return datasource{
		Name:           name,
		UID:            uid,
		Type:           "prometheus",
		Access:         "proxy",
		URL:            mimirURL + "/prometheus",
		IsDefault:      isDefault,
		JSONData:       jsonData,
		SecureJSONData: map[string]string{"httpHeaderValue1": orgID},
	}
}

// RulePlanTSV renders the rule plan for scripts/sync-rules.sh.
func RulePlanTSV(plan []RulePlanEntry) []byte {
	var b bytes.Buffer
	b.WriteString(generatedHeader)
	b.WriteString("# tenant\tnamespace\tfile\n")
	for _, e := range plan {
		fmt.Fprintf(&b, "%s\t%s\t%s\n", e.Tenant, e.Namespace, e.File)
	}
	return b.Bytes()
}

func marshal(v any) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(generatedHeader)
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return b.Bytes(), enc.Close()
}
